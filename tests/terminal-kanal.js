const assert = require('node:assert/strict');
const { randomBytes } = require('node:crypto');
const { chromium } = require('playwright');
const PF = require('./_pfad');

(async () => {
  const b = await chromium.launch();
  try {
    const p = await b.newPage({ reducedMotion:'reduce' });
    const fehler = [], netz = [];
    p.on('pageerror', e => fehler.push(e.message));
    await p.route(/^https?:/, r => { netz.push(r.request().url()); return r.abort(); });
    await p.goto(PF.APP);
    const kennung = randomBytes(16).toString('hex');
    await p.locator('#gate-pw').fill(kennung);
    if (await p.locator('#gate-pw2').isVisible()) await p.locator('#gate-pw2').fill(kennung);
    await p.click('#gate-go');
    assert.equal(await p.locator('#profil-terminal > summary').textContent(), 'Terminal');
    await p.locator('#profil-terminal > summary').click();
    const input = p.locator('#profil-terminal-eingabe'), out = p.locator('#profil-terminal-ausgabe');
    const prompt = p.locator('#profil-terminal-prompt');
    const befehl = 'secure-channel --connect --onion --ephemeral';
    const kommando = async value => { await input.fill(value); await input.press('Enter'); };
    const promptIst = value => p.waitForFunction(v => document.getElementById('profil-terminal-prompt').textContent === v, value);
    const vorher = netz.length;
    await input.fill('sec');
    await input.press('Tab');
    assert.equal(await input.inputValue(), 'secure-channel ');
    await input.press('Tab');
    assert.equal(await input.inputValue(), befehl);
    await p.emulateMedia({reducedMotion:'no-preference'});
    await p.clock.install();
    await p.clock.pauseAt(new Date(Date.now() + 1000));
    const start = await p.evaluate(() => Date.now());
    await input.press('Enter');
    await p.clock.runFor(4749);
    assert.equal(await prompt.textContent(), '…');
    await p.clock.runFor(1);
    assert.equal(await prompt.textContent(), 'you >');
    assert.equal(await p.evaluate(() => Date.now()) - start, 4750);
    const offen = await out.textContent();
    assert.doesNotMatch(offen, /Local channel simulation/);
    assert.match(offen, /Handshake complete\. Forward secrecy active\./);
    const id = offen.match(/NODE-\d{4}-[A-Z]  \(session: ([a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4})\)/)[1];
    const kontakt = offen.match(/Contact: +"([a-z]{14})"/)[1];
    await kommando('ping relay');
    assert.match(await out.textContent(), /Erwartet:/);
    await kommando('Auftrag erledigt.');
    await p.clock.runFor(14999);
    assert.doesNotMatch(await out.textContent(), /Verstanden\.|Closing channel/);
    await p.clock.runFor(1);
    assert.match(await out.textContent(), /Verstanden\./);
    await p.clock.runFor(1999);
    assert.doesNotMatch(await out.textContent(), /Closing channel/);
    await p.clock.runFor(1);
    assert.match(await out.textContent(), /Closing channel/);
    await p.clock.runFor(1950);
    assert.equal(await prompt.textContent(), 'root@terminal:~#');
    await p.clock.resume();
    await p.emulateMedia({reducedMotion:'reduce'});
    const fertig = await out.textContent();
    assert.match(fertig, /Verstanden\./);
    assert.match(fertig, /Wiping memory buffers\.\.\. \(\d+ kb\)/);
    assert.match(fertig, /Connection terminated\./);
    assert.equal(fertig.includes(id) || fertig.includes(kontakt) || fertig.includes('you > Auftrag erledigt.'), false);
    await kommando(befehl);
    await promptIst('you >');
    const neu = await out.textContent();
    assert.equal(neu.includes(id) || neu.includes(kontakt), false);
    await kommando('Auftrag gescheitert.');
    await p.clock.runFor(19000);
    await promptIst('root@terminal:~#');
    await kommando(befehl);
    await promptIst('you >');
    await input.press('Escape');
    await promptIst('root@terminal:~#');
    assert.doesNotMatch(await out.textContent(), /Contact:/);
    await kommando(befehl);
    await promptIst('you >');
    await kommando('Auftrag erledigt.');
    await kommando('exit');
    assert.equal(await p.locator('#profil-terminal').getAttribute('open'), null);
    await p.clock.runFor(19000);
    assert.equal(await p.evaluate(() => TERMINAL_ZUSTAND.kanal), null);
    assert.doesNotMatch(await out.textContent(), /Contact:|you > Auftrag/);
    await p.locator('#profil-terminal > summary').click();
    await input.fill('ex');
    await input.press('Tab');
    assert.equal(await input.inputValue(), 'exit ');
    await input.press('Enter');
    assert.equal(await p.locator('#profil-terminal').getAttribute('open'), null);
    assert.equal(netz.length, vorher);
    assert.deepEqual(fehler, []);
    console.log('OK: Secure Channel, Tab, 4,75 s Aufbau, 15 s Antwortpause, 2 s bis Disconnect, exit und keine Netzwerkanfrage');
  } finally { await b.close(); }
})().catch(e => { console.error(e); process.exitCode=1; });
